    where (f.user_id = auth.uid() and f.friend_id = case when sender_id = auth.uid() then recipient_id else sender_id end)
       or (f.friend_id = auth.uid() and f.user_id = case when sender_id = auth.uid() then recipient_id else sender_id end)
  )
