-- Unique usernames, public profiles, global community, and friend-only private chats.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'طالب',
  avatar_url text,
  updated_at timestamptz not null default now()
);
alter table public.profiles add column if not exists username text;
alter table public.profiles add column if not exists avatar_url text;
alter table public.profiles add column if not exists updated_at timestamptz not null default now();
update public.profiles set username='student_'||replace(left(id::text,8),'-','') where username is null or btrim(username)='';
create unique index if not exists profiles_username_unique_idx on public.profiles (lower(username));
alter table public.profiles alter column username set not null;
alter table public.profiles drop constraint if exists profiles_username_format;
alter table public.profiles add constraint profiles_username_format check (username ~ '^[a-z0-9_]{3,24}$');
alter table public.profiles drop constraint if exists profiles_display_name_length;
alter table public.profiles add constraint profiles_display_name_length check (char_length(display_name) between 1 and 50);
create table if not exists public.friendships (
  user_id uuid not null references auth.users(id) on delete cascade,
  friend_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, friend_id),
  constraint friendship_not_self check (user_id <> friend_id)
);
create table if not exists public.community_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 1000),
  created_at timestamptz not null default now()
);
create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 1000),
  created_at timestamptz not null default now(),
  constraint direct_message_not_self check (sender_id <> recipient_id)
);
create index if not exists community_messages_created_at_idx on public.community_messages(created_at);
create index if not exists direct_messages_pair_created_at_idx on public.direct_messages(sender_id, recipient_id, created_at);
create or replace function public.student_guide_create_profile()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  requested_username text;
  requested_name text;
begin
  requested_username := lower(coalesce(new.raw_user_meta_data->>'username',''));
  requested_name := left(coalesce(nullif(btrim(new.raw_user_meta_data->>'display_name'),''),'طالب'),50);
  if requested_username !~ '^[a-z0-9_]{3,24}$' then
    requested_username := 'student_'||replace(left(new.id::text,8),'-','');
  end if;
  insert into public.profiles(id, username, display_name)
  values(new.id, requested_username, requested_name)
  on conflict (id) do nothing;
  return new;
end;
$;
revoke all on function public.student_guide_create_profile() from public, anon, authenticated;
